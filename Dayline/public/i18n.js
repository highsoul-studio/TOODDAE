export const DICT = { ja, ko, en, zh };

let lang = 'en';
try {
  const saved = globalThis.localStorage?.getItem('lang');
  if (LANGS.some((l) => l.code === saved)) lang = saved;
} catch {}
const meta = () => LANGS.find((l) => l.code === lang);
if (globalThis.document) document.documentElement.lang = meta().html; // (テストでは Node から読み込むので document が無い)

export const getLang = () => lang;
export function setLang(code,{applyDocument=true}={}) {
  if (!LANGS.some((l) => l.code === code)) return;
  lang = code;
  if (globalThis.document&&applyDocument) document.documentElement.lang = meta().html;
  try {
    localStorage.setItem('lang', code);
  } catch {}
}

const fill = (s, vars, esc) => s.replace(/\{(\w+)\}/g, (_, k) => (vars?.[k] == null ? '' : esc ? escapeHtml(String(vars[k])) : String(vars[k])));
export const escapeHtml = (s) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const raw = (key) => DICT[lang][key] ?? DICT.ja[key] ?? key;
export const t = (key, vars) => fill(raw(key), vars, false); // プレーンテキスト
export const h = (key, vars) => fill(raw(key), vars, true); // HTML (辞書の <code>/<b> を生かし、差し込み値はエスケープ)

// ---- 日付の整形 (Intl に任せて言語ごとの表記にする) ----
const dtf = (opts) => new Intl.DateTimeFormat(meta().intl, { timeZone: 'UTC', ...opts });
const utc = (iso) => new Date(`${iso}T00:00:00Z`);
const MON = Date.UTC(2024, 0, 1); // 2024-01-01 は月曜
export const weekdayShort = (i) => dtf({ weekday: 'short' }).format(new Date(MON + i * 864e5)); // i: 0=月 … 6=日
export const weekdayLong = (iso) => dtf({ weekday: 'long' }).format(utc(iso));
export const monthDay = (iso) => dtf({ month: 'long', day: 'numeric' }).format(utc(iso));
export const monthYear = (y, m0) => dtf({ year: 'numeric', month: 'long' }).format(new Date(Date.UTC(y, m0, 1)));
export const fullDate = (iso) => dtf({ dateStyle: 'full' }).format(utc(iso));
export const dowIndex = (iso) => (utc(iso).getUTCDay() + 6) % 7;
export const dateLabel = (iso) => `${iso.replaceAll('-', '/')} (${weekdayShort(dowIndex(iso))})`;
export const md = (iso) => iso.slice(5).replace('-', '/');
